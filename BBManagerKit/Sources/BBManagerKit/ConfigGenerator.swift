    func topology(storageAddresses: [String]) -> String {
        """
        // \(Self.header)
        // Storage servers.
        local storageAddresses = [
        \(storageAddresses.map { "  \(js($0))," }.joined(separator: "\n"))
        ];

        local grpc(address) = {
          grpc: {
            client: { address: address },
            enableCompression: true,
          },
        };

        // Distribute a backend across the storage servers in a sharded manner.
        local sharded(backendForAddress) = {
          sharding: {
            shards: {
              [std.toString(i)]: {
                backend: backendForAddress(storageAddresses[i]),
                weight: 1,
              },
              for i in std.range(0, std.length(storageAddresses) - 1)
            },
          },
        };

        // Cheap cache that saves a GetCapabilities call for every CDC interaction.
        local cdcParameterCache = {
          cacheSize: 1000,
          cacheDuration: '60s',
          cacheReplacementPolicy: 'LEAST_RECENTLY_USED',
        };

        {
          chunkStorage: sharded(grpc),
          chunkMappingStorage: {
            chunkMappingValidating: {
              backend: sharded(grpc),
            },
          },
          cdcParameterCache: cdcParameterCache,
          actionCache: {
            completenessChecking: {
              backend: sharded(grpc),
              maximumTotalTreeSizeBytes: 64 * 1024 * 1024,
            },
          },
          fileSystemAccessCache: sharded(grpc),
          initialSizeClassCache: sharded(grpc),
        }

        """
    }

    func storage(_ s: StorageSettings) -> String {
        let casBytes = Self.bytes(gib: max(1, s.casSizeGiB))
        let acBytes = Self.bytes(mib: max(16, s.actionCacheSizeMiB))
        let cmsBytes = Self.bytes(mib: max(16, s.chunkMappingSizeMiB))
        let fsacBytes = Self.bytes(mib: max(16, s.fileSystemAccessCacheSizeMiB))
        let chunking = """
        chunkingParameters: {
          minChunkSizeBytes: 256 * 1024,
          horizonSizeBytes: 8 * 256 * 1024,
        },
        """
        func block(_ dir: String, _ bytes: Int64, _ ratio: Int64, newBlocks: Int, extra: String? = nil) -> String {
            Self.localBlobstore(
                directory: "/storage-\(dir)",
                blocksBytes: bytes,
                keyLocationMapBytes: Self.keyLocationMapBytes(blocks: bytes, ratio: ratio),
                newBlocks: newBlocks,
                persistent: s.persistent,
                extra: extra
            )
        }
        return """
        // \(Self.header)
        local common = import 'common.libsonnet';

        {
          grpcServers: [{
            listenAddresses: [':8981'],
            authenticationPolicy: { allow: {} },
          }],
          maximumMessageSizeBytes: common.maximumMessageSizeBytes,
          global: common.global,
          supportedCompressors: ['ZSTD'],
          contentAddressableStorageServer: {
            contentAddressableStorage: {
              chunkStorage: \(Self.indent(block("cs", casBytes, 80, newBlocks: 3, extra: chunking), 6)),
              chunkMappingStorage: \(Self.indent(block("cms", cmsBytes, 20, newBlocks: 1), 6)),
            },
            getAuthorizer: { allow: {} },
            putAuthorizer: { allow: {} },
            findMissingAuthorizer: { allow: {} },
            maximumChunkCount: 100000,
          },
          actionCache: {
            backend: \(Self.indent(block("ac", acBytes, 20, newBlocks: 1), 4)),
            getAuthorizer: { allow: {} },
            putAuthorizer: { allow: {} },
          },
          fileSystemAccessCache: {
            backend: \(Self.indent(block("fsac", fsacBytes, 20, newBlocks: 1), 4)),
            getAuthorizer: { allow: {} },
            putAuthorizer: { allow: {} },
          },
        }

        """
    }

