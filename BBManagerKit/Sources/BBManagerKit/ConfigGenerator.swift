import CryptoKit
import Foundation

/// A file that BB Manager writes into a node's directory on the remote machine.
public struct GeneratedFile: Hashable, Sendable, Identifiable {
    /// Path relative to the node directory, e.g. `config/storage.jsonnet`.
    public var path: String
    public var generated: String
    /// Content the user customised in the Files editor, if any.
    public var override: String?

    public var content: String { override ?? generated }
    public var isOverridden: Bool { override != nil }
    public var id: String { path }
}

/// Port on 127.0.0.1 where a service exposes Prometheus metrics.
public struct DiagnosticsEndpoint: Hashable, Sendable {
    public var service: String
    public var port: Int
}

/// How a node's services are run on its machine.
public enum NodeRuntime: String, Sendable {
    /// A Docker Compose project.
    case compose
    /// launchd agents running Buildbarn binaries directly (macOS).
    case launchd
}

/// Buildbarn release whose binaries a native node downloads.
public struct NativeRelease: Hashable, Sendable {
    /// GitHub release tag of buildbarn/bb-remote-execution, e.g. `20261102T094740Z-c9ba98c`.
    public var tag: String
    public var binaries: [String]
}

/// Everything needed to deploy one node (main or worker) to a machine.
public struct NodePlan: Sendable {
    public var role: NodeRole
    public var machine: Machine
    public var directory: String
    public var files: [GeneratedFile]
    /// POSIX shell run inside `directory` before `docker compose up`.
    public var prepareScript: String
    /// Long-running services (one-shot installers excluded).
    public var services: [String]
    public var diagnostics: [DiagnosticsEndpoint]
    /// Stop everything before starting again (needed for FUSE mounts).
    public var stopBeforeDeploy: Bool
    /// Host ports the node publishes, on any address.
    public var hostPorts: [Int] = []
    public var runtime: NodeRuntime = .compose
    public var nativeRelease: NativeRelease?

    /// Stable hash of the effective file contents, used to detect undeployed changes.
    public var fingerprint: String {
        var hasher = SHA256()
        for file in files.sorted(by: { $0.path < $1.path }) {
            hasher.update(data: Data(file.path.utf8))
            hasher.update(data: Data([0]))
            hasher.update(data: Data(file.content.utf8))
            hasher.update(data: Data([0]))
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

/// Renders docker-compose and Buildbarn Jsonnet configuration from the cluster model.
///
/// The output follows buildbarn/bb-deployments (docker-compose flavour), adapted so
/// the main node and workers can live on different machines.
public struct ConfigGenerator {
    public var cluster: ClusterConfiguration
    public var machines: [Machine]

    public init(cluster: ClusterConfiguration, machines: [Machine]) {
        self.cluster = cluster
        self.machines = machines
    }

    // Host ports bound to 127.0.0.1 for Prometheus scraping over SSH.
    public static let frontendDiagnosticsPort = 9980
    public static let schedulerDiagnosticsPort = 9981
    public static let portalDiagnosticsPort = 9982
    public static let workerDiagnosticsPort = 9985
    public static let storageDiagnosticsBasePort = 9990

    public static let header = "Generated by BB Manager. Customise it in BB Manager's Files tab; direct edits are overwritten on the next deploy."

    public func machine(_ id: UUID) -> Machine? { machines.first { $0.id == id } }

    public func plan(for role: NodeRole) -> NodePlan? {
        switch role {
        case .main: mainPlan()
        case .worker(let id): cluster.worker(id: id).flatMap(workerPlan)
        }
    }

    public static func directory(for role: NodeRole, on machine: Machine) -> String {
        var base = machine.installDirectory
        while base.count > 1 && base.hasSuffix("/") { base.removeLast() }
        return base + "/" + role.directoryName
    }

    // MARK: - Main node

    public func mainPlan() -> NodePlan? {
        guard let main = cluster.main, let machine = machine(main.machineID) else { return nil }
        let shards = max(1, main.storage.shards)
        let internalStorage = (0..<shards).map { "storage-\($0):8981" }

        var files: [(String, String)] = [
            ("docker-compose.yml", mainCompose(main, shards: shards)),
            ("config/common.libsonnet", common(main)),
            ("config/topology.libsonnet", topology(storageAddresses: internalStorage)),
            ("config/storage.jsonnet", storage(main.storage)),
            ("config/frontend.jsonnet", frontend(main)),
            ("config/scheduler.jsonnet", scheduler(main.scheduler)),
        ]
        if main.portal.enabled {
            files.append(("config/portal.jsonnet", portal(main)))
        }

        var services = ["frontend"] + (0..<shards).map { "storage-\($0)" } + ["scheduler"]
        var diagnostics = [
            DiagnosticsEndpoint(service: "frontend", port: Self.frontendDiagnosticsPort),
            DiagnosticsEndpoint(service: "scheduler", port: Self.schedulerDiagnosticsPort),
        ]
        diagnostics += (0..<shards).map {
            DiagnosticsEndpoint(service: "storage-\($0)", port: Self.storageDiagnosticsBasePort + $0)
        }
        if main.portal.enabled {
            services += ["portal", "postgres"]
            diagnostics.append(DiagnosticsEndpoint(service: "portal", port: Self.portalDiagnosticsPort))
        }

        var hostPorts = [main.frontendPort, main.schedulerWorkerPort, 8984]
        hostPorts += (0..<shards).map { main.storageBasePort + $0 }
        hostPorts += diagnostics.map(\.port)
        if main.portal.enabled {
            hostPorts += [main.portal.httpPort, main.portal.besPort]
        }

        return NodePlan(
            role: .main,
            machine: machine,
            directory: Self.directory(for: .main, on: machine),
            files: files.map { GeneratedFile(path: $0.0, generated: $0.1, override: main.fileOverrides[$0.0]) },
            prepareScript: mainPrepareScript(main, shards: shards),
            services: services,
            diagnostics: diagnostics,
            stopBeforeDeploy: false,
            hostPorts: hostPorts.sorted()
        )
    }

    func mainPrepareScript(_ main: MainNodeSettings, shards: Int) -> String {
        let s = main.storage
        let layout = Self.shortHash("\(shards)|\(s.casSizeGiB)|\(s.actionCacheSizeMiB)|\(s.chunkMappingSizeMiB)|\(s.fileSystemAccessCacheSizeMiB)|\(s.persistent)")
        var dirs: [String] = []
        for i in 0..<shards {
            for kind in ["ac", "cs", "cms", "fsac"] {
                dirs.append("volumes/storage-\(kind)-\(i)")
                dirs.append("volumes/storage-\(kind)-\(i)/persistent_state")
            }
        }
        var script = """
        LAYOUT='\(layout)'
        if [ -d volumes ] && [ "$(cat volumes/.storage-layout 2>/dev/null)" != "$LAYOUT" ]; then
          echo "Storage size or sharding changed: clearing cached blobs."
          $DC down --remove-orphans || true
          rm -rf volumes/storage-*
        fi
        mkdir -p volumes
        printf '%s' "$LAYOUT" > volumes/.storage-layout
        mkdir -p \(dirs.joined(separator: " "))
        chmod 0700 \(dirs.joined(separator: " "))

        """
        if main.portal.enabled {
            script += "mkdir -p volumes/postgres\n"
        }
        return script
    }

    func mainCompose(_ main: MainNodeSettings, shards: Int) -> String {
        let images = cluster.images
        var y = "# \(Self.header)\nname: buildbarn-main\nservices:\n"
        y += """
          frontend:
            image: \(yaml(images.storage))
            command: ["/config/frontend.jsonnet"]
            restart: unless-stopped
            ports:
              - "\(main.frontendPort):8980"
              - "127.0.0.1:\(Self.frontendDiagnosticsPort):9980"
            volumes:
              - ./config:/config:ro

        """
        for i in 0..<shards {
            y += """
              storage-\(i):
                image: \(yaml(images.storage))
                command: ["/config/storage.jsonnet"]
                restart: unless-stopped
                ports:
                  - "\(main.storageBasePort + i):8981"
                  - "127.0.0.1:\(Self.storageDiagnosticsBasePort + i):9980"
                volumes:
                  - ./config:/config:ro
                  - ./volumes/storage-ac-\(i):/storage-ac
                  - ./volumes/storage-cs-\(i):/storage-cs
                  - ./volumes/storage-cms-\(i):/storage-cms
                  - ./volumes/storage-fsac-\(i):/storage-fsac

            """
        }
        y += """
          scheduler:
            image: \(yaml(images.scheduler))
            command: ["/config/scheduler.jsonnet"]
            restart: unless-stopped
            ports:
              - "\(main.schedulerWorkerPort):8983"
              - "127.0.0.1:8984:8984"
              - "127.0.0.1:\(Self.schedulerDiagnosticsPort):9980"
            volumes:
              - ./config:/config:ro

        """
        if main.portal.enabled {
            y += """
              portal:
                image: \(yaml(images.portal))
                command: ["/config/portal.jsonnet"]
                restart: unless-stopped
                ports:
                  - "\(main.portal.httpPort):8081"
                  - "\(main.portal.besPort):8082"
                  - "127.0.0.1:\(Self.portalDiagnosticsPort):9980"
                volumes:
                  - ./config:/config:ro
                depends_on:
                  postgres:
                    condition: service_healthy
                    restart: true

              postgres:
                image: \(yaml(images.postgres))
                restart: unless-stopped
                environment:
                  POSTGRES_DB: app
                  POSTGRES_USER: app
                  POSTGRES_PASSWORD: \(yaml(main.portal.databasePassword))
                volumes:
                  - ./volumes/postgres:/var/lib/postgresql
                healthcheck:
                  test: ["CMD-SHELL", "pg_isready -U $${POSTGRES_USER} -d $${POSTGRES_DB}"]
                  interval: 10s
                  retries: 5
                  start_period: 30s
                  timeout: 10s

            """
        }
        return y
    }

