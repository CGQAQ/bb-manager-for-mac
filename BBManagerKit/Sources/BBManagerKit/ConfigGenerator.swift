    /// `.bazelrc` lines that point Bazel at this cluster.
    public func bazelrc(configName: String = "bb") -> String? {
        guard let main = cluster.main else { return nil }
        let settings = cluster.workers.first?.settings ?? cluster.workerDefaults
        var lines = [
            "build:\(configName) --remote_executor=grpc://\(main.advertisedAddress):\(main.frontendPort)",
            "build:\(configName) --remote_instance_name=\(settings.instanceNamePrefix)",
        ]
        for prop in settings.effectivePlatformProperties {
            lines.append("build:\(configName) --remote_default_exec_properties=\(prop.name)=\(prop.value)")
        }
        if main.portal.enabled {
            lines.append("build:\(configName) --bes_backend=grpc://\(main.advertisedAddress):\(main.portal.besPort)")
        }
        lines.append("build:\(configName) --remote_timeout=3600")
        lines.append("build:\(configName) --jobs=\(max(16, totalExecutorSlots * 2))")
        return lines.joined(separator: "\n")
    }

    public var totalExecutorSlots: Int {
        cluster.workers.reduce(0) { $0 + max(1, $1.settings.concurrency) }
    }

    // MARK: - Formatting helpers

    func js(_ value: String) -> String { Self.jsonnetString(value) }
    func yaml(_ value: String) -> String { Self.yamlString(value) }

    public static func jsonnetString(_ value: String) -> String {
        let escaped = value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "'", with: "\\'")
            .replacingOccurrences(of: "\n", with: "\\n")
        return "'\(escaped)'"
    }

    public static func yamlString(_ value: String) -> String {
        let escaped = value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: "\\n")
        return "\"\(escaped)\""
    }

    static let mib: Int64 = 1024 * 1024
    static let gib: Int64 = 1024 * 1024 * 1024

    static func bytes(gib value: Double) -> Int64 { Int64((value * 1024).rounded()) * mib }
    static func bytes(mib value: Double) -> Int64 { Int64(value.rounded()) * mib }

    static func keyLocationMapBytes(blocks: Int64, ratio: Int64) -> Int64 {
        let raw = blocks / ratio
        let rounded = ((raw + mib - 1) / mib) * mib
        return max(mib, rounded)
    }

    /// Renders a byte count as a readable Jsonnet expression.
    public static func sizeExpression(_ bytes: Int64) -> String {
        if bytes >= gib && bytes % gib == 0 { return "\(bytes / gib) * 1024 * 1024 * 1024" }
        if bytes >= mib && bytes % mib == 0 { return "\(bytes / mib) * 1024 * 1024" }
        return "\(bytes)"
    }

    static func localBlobstore(directory: String, blocksBytes: Int64, keyLocationMapBytes: Int64, newBlocks: Int, persistent: Bool, extra: String?) -> String {
        var lines = """
        {
          'local': {
            keyLocationMap: {
              onBlockDevice: {
                file: {
                  path: '\(directory)/key_location_map',
                  sizeBytes: \(sizeExpression(keyLocationMapBytes)),
                },
              },
              maximumGetAttempts: 16,
              maximumPutAttempts: 64,
            },
            oldBlocks: 8,
            currentBlocks: 24,
            newBlocks: \(newBlocks),
            blocksOnBlockDevice: {
              source: {
                file: {
                  path: '\(directory)/blocks',
                  sizeBytes: \(sizeExpression(blocksBytes)),
                },
              },
              spareBlocks: 3,
            },

        """
        if persistent {
            lines += """
                persistent: {
                  stateDirectoryPath: '\(directory)/persistent_state',
                  minimumEpochInterval: '300s',
                },

            """
        }
        if let extra {
            lines += indent(extra, 4, includeFirstLine: true) + "\n"
        }
        lines += "  },\n}"
        return lines
    }

    /// Indents every line after the first (or all lines) by `spaces`.
    static func indent(_ text: String, _ spaces: Int, includeFirstLine: Bool = false) -> String {
        let pad = String(repeating: " ", count: spaces)
        return text
            .split(separator: "\n", omittingEmptySubsequences: false)
            .enumerated()
            .map { index, line in
                if line.isEmpty || (index == 0 && !includeFirstLine) { return String(line) }
                return pad + line
            }
            .joined(separator: "\n")
    }

    static func shortHash(_ text: String) -> String {
        SHA256.hash(data: Data(text.utf8)).prefix(8).map { String(format: "%02x", $0) }.joined()
    }
