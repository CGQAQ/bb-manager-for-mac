    // MARK: - Worker node

    public func workerPlan(_ worker: WorkerNode) -> NodePlan? {
        guard let main = cluster.main, let machine = machine(worker.machineID) else { return nil }
        if worker.settings.kind.isNative {
            return nativeWorkerPlan(worker, main: main, machine: machine)
        }
        let shards = max(1, main.storage.shards)
        let externalStorage = (0..<shards).map { "\(main.advertisedAddress):\(main.storageBasePort + $0)" }
        let settings = worker.settings
        let files: [(String, String)] = [
            ("docker-compose.yml", workerCompose(settings)),
            ("config/common.libsonnet", common(main)),
            ("config/topology.libsonnet", topology(storageAddresses: externalStorage)),
            ("config/worker.jsonnet", settings.kind == .fuse
                ? fuseWorker(settings, main: main, machine: machine)
                : hardlinkingWorker(settings, main: main, machine: machine)),
            ("config/runner.jsonnet", runner()),
        ]
        return NodePlan(
            role: .worker(worker.id),
            machine: machine,
            directory: Self.directory(for: .worker(worker.id), on: machine),
            files: files.map { GeneratedFile(path: $0.0, generated: $0.1, override: worker.fileOverrides[$0.0]) },
            prepareScript: workerPrepareScript(settings),
            services: ["worker", "runner"],
            diagnostics: [DiagnosticsEndpoint(service: "worker", port: Self.workerDiagnosticsPort)],
            stopBeforeDeploy: true,
            hostPorts: [Self.workerDiagnosticsPort]
        )
    }

    func workerPrepareScript(_ s: WorkerSettings) -> String {
        let layout = Self.shortHash("\(s.kind.rawValue)|\(s.localCacheSizeGiB)|\(s.maximumCacheFileCount)")
        return """
        umount volumes/worker/build 2>/dev/null || umount -l volumes/worker/build 2>/dev/null || true
        LAYOUT='\(layout)'
        if [ -d volumes ] && [ "$(cat volumes/.cache-layout 2>/dev/null)" != "$LAYOUT" ]; then
          echo "Worker cache settings changed: clearing local cache."
          rm -rf volumes/worker/cs volumes/worker/cache volumes/worker/filepool
        fi
        mkdir -p volumes/bb volumes/worker/build volumes/worker/cs/persistent_state volumes/worker/cache
        printf '%s' "$LAYOUT" > volumes/.cache-layout
        chmod 0777 volumes/worker volumes/worker/build volumes/worker/cs volumes/worker/cs/persistent_state
        chmod 0700 volumes/worker/cache
        rm -f volumes/bb/installed

        """
    }

    func workerCompose(_ s: WorkerSettings) -> String {
        let images = cluster.images
        let fuse = s.kind == .fuse
        let workerMount: String
        let runnerMount: String
        if fuse {
            workerMount = """
                  - type: bind
                    source: ./volumes/worker
                    target: /worker
                    bind:
                      propagation: shared
            """
            runnerMount = """
                  - type: bind
                    source: ./volumes/worker
                    target: /worker
                    bind:
                      propagation: slave
            """
        } else {
            workerMount = "      - ./volumes/worker:/worker"
            runnerMount = "      - ./volumes/worker:/worker"
        }
        return """
        # \(Self.header)
        name: buildbarn-worker
        services:
          runner-installer:
            image: \(yaml(images.runnerInstaller))
            volumes:
              - ./volumes/bb:/bb

          worker:
            image: \(yaml(images.worker))
            command: ["/config/worker.jsonnet"]
            restart: unless-stopped
            privileged: \(fuse ? "true" : "false")
            ports:
              - "127.0.0.1:\(Self.workerDiagnosticsPort):9980"
            volumes:
              - ./config:/config:ro
        \(workerMount)

          runner:
            image: \(yaml(s.runnerImage))
            command:
              - sh
              - -c
              - while ! test -f /bb/installed; do sleep 1; done; exec /bb/bb_runner /config/runner.jsonnet
            restart: unless-stopped
            network_mode: none
            volumes:
              - ./config:/config:ro
              - ./volumes/bb:/bb
        \(runnerMount)
            depends_on:
              - runner-installer

        """
    }

    func platformBlock(_ s: WorkerSettings) -> String {
        let props = s.effectivePlatformProperties
            .map { "{ name: \(js($0.name)), value: \(js($0.value)) }," }
            .joined(separator: "\n")
        return "platform: {\n  properties: [\n\(Self.indent(props, 4, includeFirstLine: true))\n  ],\n},"
    }

    func workerID(_ machine: Machine) -> String {
        "workerId: {\n  hostname: \(js(machine.host)),\n  node: \(js(machine.displayName)),\n},"
    }

    func fuseWorker(_ s: WorkerSettings, main: MainNodeSettings, machine: Machine) -> String {
        let concurrency = max(1, s.concurrency)
        let cacheBytes = Self.bytes(gib: max(1, s.localCacheSizeGiB))
        let perAction = Self.bytes(gib: max(0.125, s.filePoolPerActionGiB))
        let localCache = Self.localBlobstore(
            directory: "/worker/cs",
            blocksBytes: cacheBytes,
            keyLocationMapBytes: Self.keyLocationMapBytes(blocks: cacheBytes, ratio: 80),
            newBlocks: 3,
            persistent: true,
            extra: nil
        )
        return """
        // \(Self.header)
